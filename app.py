def make_projection_curve(
    current_year: int,
    current_absorption_tons: float,
    projected_absorption_tons: float,
    horizon_year: int = 2050,
) -> pd.DataFrame:
    """Visualization-only curve between current and target year (saturating
    interpolation) — intermediate years are for the chart, not a second
    calculation."""
    years = np.arange(current_year, horizon_year + 1)
    t = (years - current_year) / max(horizon_year - current_year, 1)

    curve = (1 - np.exp(-3.2 * t)) / (1 - np.exp(-3.2))
    absorption = current_absorption_tons + curve * (projected_absorption_tons - current_absorption_tons)

    return pd.DataFrame({"year": years, "absorption_tons": absorption})


