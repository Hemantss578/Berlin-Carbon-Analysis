@st.cache_data(show_spinner="Loading PLZ boundaries…")
def load_plz_features_geo() -> gpd.GeoDataFrame:
    gdf = gpd.read_file(PLZ_FEATURES_GEOJSON)
    if gdf.crs is None:
        gdf = gdf.set_crs("EPSG:4326", allow_override=True)
    else:
        gdf = gdf.to_crs("EPSG:4326")
    gdf["PLZ"] = gdf["PLZ"].astype(str)
    gdf["bezirk"] = gdf["bezirk"].fillna("—")
    return gdf


@st.cache_data(show_spinner="Loading tree inventory (691k rows, first load only)…")
def load_trees_enriched() -> pd.DataFrame:
    df = pd.read_parquet(TREES_ENRICHED_PARQUET)
    df["PLZ"] = df["PLZ"].astype(str)
    return df


@st.cache_data(show_spinner=False)
def load_bezirke() -> gpd.GeoDataFrame | None:
    """Real Berlin borough boundaries with real names, merged with real
    (partial — 2/12 boroughs as of this writing) Bezirk-level CO2 data.
    Returns None if the vendored boundary file isn't present (map still
    works, just without area-name labels)."""
    if not BEZIRKE_GEOJSON.exists():
        return None
    gdf = gpd.read_file(BEZIRKE_GEOJSON)
    if gdf.crs is None:
        gdf = gdf.set_crs("EPSG:4326", allow_override=True)
    else:
        gdf = gdf.to_crs("EPSG:4326")
    gdf["name"] = gdf["spatial_alias"]

    emissions_df = try_load_real_bezirk_emissions()
    if emissions_df is not None and len(emissions_df):
        gdf = gdf.merge(emissions_df.rename(columns={"bezirk": "name"}), on="name", how="left")
    else:
        gdf["total_co2_tons"] = np.nan
        gdf["year"] = np.nan

    gdf["co2_display"] = gdf.apply(
        lambda r: f"{r['total_co2_tons']:,.0f} t ({int(r['year'])})"
        if pd.notna(r["total_co2_tons"])
        else "not yet published",
        axis=1,
    )
    return gdf


@st.cache_resource(show_spinner="Loading models…")
def load_models() -> Tuple[object, dict]:
    kmeans_pipeline = joblib.load(KMEANS_PIPELINE_PATH)
